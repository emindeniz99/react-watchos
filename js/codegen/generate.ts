const JSON_VALUE_SWIFT = `public enum JSONValue: Codable, Equatable, Sendable {
    case string(String)
    case number(Double)
    case bool(Bool)
    case array([JSONValue])
    case object([String: JSONValue])
    case null

    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
        } else if let bool = try? container.decode(Bool.self) {
            self = .bool(bool)
        } else if let number = try? container.decode(Double.self) {
            self = .number(number)
        } else if let string = try? container.decode(String.self) {
            self = .string(string)
        } else if let array = try? container.decode([JSONValue].self) {
            self = .array(array)
        } else if let object = try? container.decode([String: JSONValue].self) {
            self = .object(object)
        } else {
            throw DecodingError.dataCorruptedError(
                in: container, debugDescription: "Unsupported JSON value")
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .string(let value): try container.encode(value)
        case .number(let value): try container.encode(value)
        case .bool(let value): try container.encode(value)
        case .array(let value): try container.encode(value)
        case .object(let value): try container.encode(value)
        case .null: try container.encodeNil()
        }
    }
}`;

const nodeSwift =
  () => `public struct ${node.swift}: Codable, Equatable, Identifiable, Sendable {
    public let id: Int
    public let type: String
    public let props: [String: JSONValue]
    public let children: [${node.swift}]

    public func string(_ key: String) -> String? {
        if case .string(let value)? = props[key] { return value }
        return nil
    }

    public func double(_ key: String) -> Double? {
        if case .number(let value)? = props[key] { return value }
        return nil
    }

    public func bool(_ key: String) -> Bool? {
        if case .bool(let value)? = props[key] { return value }
        return nil
    }

    public func stringArray(_ key: String) -> [String]? {
        guard case .array(let values)? = props[key] else { return nil }
        return values.compactMap {
            if case .string(let value) = $0 { return value }
            return nil
        }
    }
}`;

function swiftStruct(def: StructDef) {
  const lines = [`public struct ${def.swift}: Codable, Equatable, Sendable {`];
  for (const f of def.fields) {
    if (f.doc) lines.push(`    /// ${f.doc}`);
    lines.push(`    public let ${f.name}: ${f.swift}`);
  }
  for (const computed of def.swiftComputed ?? []) {
    lines.push("");
    lines.push(`    public ${computed}`);
  }
  lines.push("}");
  return lines.join("\n");
}

// One unified module (ReactWatchCore) for both the watch host and the widget,
// so JSONValue + RNNode are defined once. All `public` for cross-module use.
function swiftModel() {
  const parts = [
    banner(),
    "import Foundation",
    "",
    JSON_VALUE_SWIFT,
    "",
    nodeSwift(),
  ];
  for (const def of structs) parts.push("", swiftStruct(def));
  // Expose the committed-tree wire version so the runtime can flag a
  // renderer-vs-runtime mismatch (see ReactAppModel.decode).
  parts.push(
    "",
    "public enum RNWire {",
    `    public static let version = ${wireVersion}`,
    `    public static let bridgeProtocol = ${bridgeProtocol}`,
    "}",
  );
  const swiftSet = (target: WireTarget) =>
    `[${featuresFor(target)
      .map((f) => `"${f}"`)
      .join(", ")}]`;
  parts.push(
    "",
    "/// The capability features each native target provides (ARCH-01). A bundle",
    "/// runs only if its required features are a subset (see CapabilityGate).",
    "public enum HostFeatures {",
    `    public static let watch: Set<String> = ${swiftSet("watch")}`,
    `    public static let widget: Set<String> = ${swiftSet("widget")}`,
    "}",
  );
  // via:"invoke" methods aren't installed as host functions, so the ARCH-07
  // install guards can't gate them — the invoke dispatcher checks this map
  // before routing instead.
  const invokeMethods = hostMethods
    .filter((m) => m.via === "invoke")
    .sort((a, b) => (a.name < b.name ? -1 : 1));
  parts.push(
    "",
    "/// Feature id for each invoke-routed host method (ARCH-07). The host checks",
    "/// it BEFORE dispatching an invoke, so a feature the consumer's HostPolicy",
    "/// didn't authorize rejects typed (POLICY_DENIED) instead of reaching a",
    "/// handler.",
    "public enum HostInvokeFeatures {",
    "    public static let byMethod: [String: String] = [",
    ...invokeMethods.map((m) => `        "${m.name}": "${m.feature}",`),
    "    ]",
    "}",
  );
  return `${parts.join("\n")}\n`;
}

// --- Invoke channel shapes (ARCH-11) ---------------------------------------
// The `via:"invoke"` methods' request/result shapes are a CONTRACT, not a
// runtime dependency: TS interfaces land in the wire module (so a caller and a
// fixture can be typed by them), and the Swift side is emitted into the TEST
// target only. The 31 handlers keep their own decoders — see the doc on
// `invokeShapes` for why the generated-Codable-handler variant was rejected —
// so emitting these structs into ReactWatchCore would put ~20 types nobody
// instantiates into both shipping binaries, including the widget extension.

const invokeMethods = hostMethods.filter((m) => m.via === "invoke");
const shapeByTs = new Map(invokeShapes.map((s) => [s.ts, s]));

/** Splits a `HostMethod.request`/`.response` ref into its shape + arrayness.
 *  `"opaque"` returns null — the payload is the app's own JSON by contract. */
function resolveShape(
  ref: string | undefined,
): { def: StructDef; array: boolean } | null {
  if (!ref || ref === "opaque") return null;
  const array = ref.endsWith("[]");
  const name = array ? ref.slice(0, -2) : ref;
  const def = shapeByTs.get(name);
  if (!def) throw new Error(`unknown invoke shape "${name}"`);
  return { def, array };
}

/** `{ method: { request?, response? } }` — the shape refs as DATA, so the JS
 *  contract test can assert it covers every payload-carrying method without
 *  re-listing them. `"opaque"` is carried through verbatim. */
function invokeShapesTS() {
  const table: Record<string, { request?: string; response?: string }> = {};
  for (const m of invokeMethods) {
    if (!m.request && !m.response) continue;
    table[m.name] = {
      ...(m.request ? { request: m.request } : {}),
      ...(m.response ? { response: m.response } : {}),
    };
  }
  return [
    "/** ARCH-11: the declared request/result shape of each `via:\"invoke\"`",
    " *  method that carries one. A value of `\"opaque\"` means the payload is the",
    " *  consuming app's own JSON by contract (the connectivity channels), not an",
    " *  undeclared shape. Methods absent from this table send no payload and",
    " *  return void/null, a bare string, `string[]`, or a boolean. */",
    `export const INVOKE_SHAPES = ${JSON.stringify(table)} as const;`,
  ].join("\n");
}

/** The Swift half — Codable mirrors of `invokeShapes` plus per-method decode
 *  tables, emitted into the test target. Internal (not `public`): nothing
 *  outside `swift test` may depend on these. */
function invokeShapesSwift() {
  const struct = (def: StructDef) => {
    const lines = [];
    if (def.doc) lines.push(`/// ${def.doc}`);
    lines.push(`struct ${def.swift}: InvokeShape {`);
    for (const f of def.fields) {
      if (f.doc) lines.push(`    /// ${f.doc}`);
      lines.push(`    let ${f.name}: ${f.swift}`);
    }
    lines.push(
      `    static let declaredKeys: Set<String> = [${def.fields
        .map((f) => `"${f.name}"`)
        .join(", ")}]`,
    );
    lines.push("}");
    return lines.join("\n");
  };
  const entry = (m: HostMethod, ref: string | undefined) => {
    const shape = resolveShape(ref);
    if (!shape) return null;
    const call = shape.array
      ? `try decodeStrict(arrayOf: ${shape.def.swift}.self, from: $0)`
      : `try decodeStrict(${shape.def.swift}.self, from: $0)`;
    return `        "${m.name}": { ${call} },`;
  };
  const requests = invokeMethods
    .map((m) => entry(m, m.request))
    .filter((line) => line !== null);
  const responses = invokeMethods
    .map((m) => entry(m, m.response))
    .filter((line) => line !== null);
  const opaque = invokeMethods
    .filter((m) => m.request === "opaque")
    .map((m) => `"${m.name}"`);
  return `${[
    banner(),
    "import Foundation",
    "import ReactWatchCore",
    "",
    "// The SD-1 invoke channel's schema-declared shapes (ARCH-11), rendered for",
    "// the TEST target only: InvokeContractTests decodes the JS-produced",
    "// Fixtures/invoke-*.json with these, so a wrapper that changes its payload",
    "// (or a native result that changes its keys) fails `swift test` instead of",
    "// on a watch. The 31 handlers keep their own decoders by design.",
    "//",
    "// The decode is STRICT about undeclared keys, because a synthesized",
    "// `Codable` init ignores unknown keys AND maps a missing key for an",
    "// Optional property to nil — so a plain decode is blind to every rename or",
    "// addition of an OPTIONAL field (the majority of the declared surface), and",
    "// the JS suite would just rewrite the fixture around the drift. A rename",
    "// always shows up as (tolerated missing key) + (extra unknown key), so",
    "// rejecting unknown keys catches renames and additions with one check.",
    "",
    "protocol InvokeShape: Codable, Equatable {",
    "    /// Every key the schema declares for this shape.",
    "    static var declaredKeys: Set<String> { get }",
    "}",
    "",
    "struct UndeclaredInvokeKeys: Error, CustomStringConvertible {",
    "    let shape: String",
    "    let keys: [String]",
    "    var description: String {",
    '        "\\(shape) has undeclared payload keys \\(keys.sorted()) — the schema "',
    '            + "does not declare them, so no handler reads them"',
    "    }",
    "}",
    "",
    "private func assertDeclared<T: InvokeShape>(",
    "    _: T.Type, _ object: [String: JSONValue]",
    ") throws {",
    "    let extra = Set(object.keys).subtracting(T.declaredKeys)",
    "    guard extra.isEmpty else {",
    '        throw UndeclaredInvokeKeys(shape: "\\(T.self)", keys: Array(extra))',
    "    }",
    "}",
    "",
    "func decodeStrict<T: InvokeShape>(_ type: T.Type, from data: Data) throws {",
    "    _ = try JSONDecoder().decode(T.self, from: data)",
    "    try assertDeclared(",
    "        type, try JSONDecoder().decode([String: JSONValue].self, from: data))",
    "}",
    "",
    "func decodeStrict<T: InvokeShape>(arrayOf type: T.Type, from data: Data) throws {",
    "    _ = try JSONDecoder().decode([T].self, from: data)",
    "    for object in try JSONDecoder().decode(",
    "        [[String: JSONValue]].self, from: data)",
    "    {",
    "        try assertDeclared(type, object)",
    "    }",
    "}",
    "",
    ...invokeShapes.map(struct).flatMap((s) => [s, ""]),
    "enum InvokeShapes {",
    "    /// method -> decode this fixture as the declared REQUEST shape.",
    "    static let requestDecoders: [String: @Sendable (Data) throws -> Void] = [",
    ...requests,
    "    ]",
    "",
    "    /// method -> decode this fixture as the declared RESULT shape.",
    "    static let responseDecoders: [String: @Sendable (Data) throws -> Void] = [",
    ...responses,
    "    ]",
    "",
    "    /// Payloads that are the consuming app's own JSON by contract — Swift",
    "    /// hands them to WCSession as [String: Any] without reading a field, so",
    "    /// no schema can (or should) describe them.",
    `    static let opaqueRequests: Set<String> = [${opaque.join(", ")}]`,
    "}",
  ]
    .join("\n")
    .trimEnd()}\n`;
}

