/** The unique capability features a native `target` provides (ARCH-01),
 *  derived from the host methods it installs. */
const featuresFor = (target: WireTarget) =>
  [
    ...new Set(
      hostMethods
        .filter((m) => m.targets.includes(target))
        .map((m) => m.feature),
    ),
  ].sort();

// --- Host bridge (CX-023) --------------------------------------------------
// The synchronous `__host` surface is generated end-to-end from the method
// signatures: the TS `QuickJSHostGlobal`, the Swift `HostBridge` callbacks, the
// C trampolines, and the install table. `via: "invoke"` methods are routed
// through the generic channel, so they're not part of this surface.

/** Methods installed as direct host functions (everything not via invoke). */
const directMethods = hostMethods.filter((m) => m.via !== "invoke");

const SWIFT_ARG: Record<ArgType, string> = {
  string: "String",
  int: "Int",
  double: "Double",
};
const SWIFT_RET: Record<ReturnType, string> = {
  void: "Void",
  "string?": "String?",
  int: "Int",
};
const TS_ARG: Record<ArgType, string> = {
  string: "string",
  int: "number",
  double: "number",
};
const TS_RET: Record<ReturnType, string> = {
  void: "void",
  "string?": "string | null",
  int: "number",
};

const argsOf = (m: HostMethod): HostArg[] => m.args ?? [];
const retOf = (m: HostMethod): ReturnType => m.returns ?? "void";
/** C trampoline name for a method, lowerCamelCase (swift-format requires it). */
const trampoline = (m: HostMethod) =>
  `host${m.name[0].toUpperCase()}${m.name.slice(1)}`;

/** Swift closure type for a method, e.g. `((String, Int) -> Int)`. */
function swiftClosureType(m: HostMethod) {
  const params = argsOf(m)
    .map((a) => SWIFT_ARG[a.type])
    .join(", ");
  return `((${params}) -> ${SWIFT_RET[retOf(m)]})`;
}

/** One generated C trampoline: recover the runtime, marshal args by type, call
 *  the bridge closure, marshal the return. @convention(c) can't capture, so the
 *  runtime is recovered from the context opaque pointer. */
function swiftTrampoline(m: HostMethod) {
  const args = argsOf(m);
  const ret = retOf(m);
  const fail =
    ret === "string?"
      ? "qjs_null()"
      : ret === "int"
        ? "JS_NewInt32(ctx, 0)"
        : "qjs_undefined()";
  // A zero-arg method reads neither argv nor argc, so binding them would only
  // produce an unused-value warning (and an always-true `argc >= 0`).
  const guard = [
    "let runtime = JSRuntime.from(context: ctx)",
    ...(args.length > 0 ? ["let argv", `argc >= ${args.length}`] : []),
    ...args
      .map((a, i) => [a, i] as const)
      .filter(([a]) => a.type === "string")
      .map(([, i]) => `let arg${i}Cstr = JS_ToCString(ctx, argv[${i}])`),
  ].join(", ");

  const body: string[] = [];
  for (const [a, i] of args.map((a, i) => [a, i] as const)) {
    if (a.type === "string")
      body.push(`let arg${i} = String(cString: arg${i}Cstr)`);
  }
  for (const [a, i] of args.map((a, i) => [a, i] as const)) {
    if (a.type === "string") body.push(`JS_FreeCString(ctx, arg${i}Cstr)`);
  }
  for (const [a, i] of args.map((a, i) => [a, i] as const)) {
    if (a.type === "int") {
      body.push(
        `var arg${i}: Int32 = 0`,
        `JS_ToInt32(ctx, &arg${i}, argv[${i}])`,
      );
    } else if (a.type === "double") {
      body.push(
        `var arg${i}: Double = 0`,
        `JS_ToFloat64(ctx, &arg${i}, argv[${i}])`,
      );
    }
  }
  const callArgs = args
    .map((a, i) => (a.type === "int" ? `Int(arg${i})` : `arg${i}`))
    .join(", ");
  const call = `runtime.bridge.${m.name}?(${callArgs})`;
  if (ret === "void") {
    body.push(call, "return qjs_undefined()");
  } else if (ret === "int") {
    body.push(
      `let result = ${call} ?? 0`,
      "return JS_NewInt32(ctx, Int32(result))",
    );
  } else {
    body.push(`guard let result = ${call} else { return qjs_null() }`);
    body.push("return JS_NewString(ctx, result)");
  }

  return [
    `private func ${trampoline(m)}(`,
    "    ctx: OpaquePointer?, thisVal _: JSValue, argc: Int32,",
    "    argv: UnsafeMutablePointer<JSValue>?",
    ") -> JSValue {",
    `    guard ${guard}`,
    `    else { return ${fail} }`,
    ...body.map((l) => `    ${l}`),
    "}",
  ].join("\n");
}

function hostBridgeSwift() {
  const fields = directMethods.map(
    (m) => `    public var ${m.name}: ${swiftClosureType(m)}?`,
  );
  const installLine = (m: HostMethod) =>
    `        JS_SetPropertyStr(\n            context, host, "${m.name}",\n            JS_NewCFunction(context, ${trampoline(m)}, "${m.name}", ${argsOf(m).length}))`;
  // One target group's install lines, grouped by feature in schema
  // (first-appearance) order — deterministic, and each feature's methods are
  // contiguous in the schema today, so the method order is unchanged. "core"
  // installs stay unconditional (a policy must not be able to brick
  // commit/log/timers/invoke); every other feature's block is wrapped in an
  // `allows(...)` guard (ARCH-07). Order across features doesn't matter
  // semantically: each line is an independent property-set on `host`.
  const guardedInstalls = (methods: HostMethod[]): string[] => {
    const groups = new Map<string, HostMethod[]>();
    for (const m of methods) {
      const group = groups.get(m.feature);
      if (group) group.push(m);
      else groups.set(m.feature, [m]);
    }
    const lines: string[] = [];
    for (const [feature, group] of groups) {
      if (feature === "core") {
        lines.push(...group.map(installLine));
      } else {
        lines.push(`        if allows("${feature}") {`);
        lines.push(...group.map((m) => `    ${installLine(m)}`));
        lines.push("        }");
      }
    }
    return lines;
  };
  // Group the installs by target: shared functions go on every embedding;
  // watch-only ones are omitted in the widget extension so JS feature detection
  // (typeof __host.fetch) is correct there and a stray call fails loudly instead
  // of hanging on a nil-backed no-op trampoline (the widget never sets those).
  const inTarget = (m: HostMethod, t: WireTarget) => m.targets.includes(t);
  const sharedInstalls = guardedInstalls(
    directMethods.filter((m) => inTarget(m, "watch") && inTarget(m, "widget")),
  );
  const watchOnlyInstalls = guardedInstalls(
    directMethods.filter((m) => inTarget(m, "watch") && !inTarget(m, "widget")),
  );
  const widgetOnlyInstalls = guardedInstalls(
    directMethods.filter((m) => !inTarget(m, "watch") && inTarget(m, "widget")),
  );
  const targetedBlock = (installs: string[], target: string) =>
    installs.length === 0
      ? []
      : [
          `        if target == .${target} {`,
          ...installs.map((l) => `    ${l}`),
          "        }",
        ];
  return `${[
    banner(),
    "import CQuickJS",
    "",
    "/// Which embedding is installing the bridge — selects which host functions",
    "/// are exposed on `__host`. Generated from each method's schema `targets`.",
    "public enum HostTarget: Sendable {",
    "    case watch",
    "    case widget",
    "}",
    "",
    "/// Every synchronous `__host` callback the JS bridge dispatches to. The",
    "/// embedding host (ReactWatchHost / IntentRuntime) sets the feature closures;",
    "/// JSRuntime sets the infra ones (setTimer/clearTimer/log) to internal",
    '/// defaults. `via: "invoke"` methods are NOT here — they go through the',
    "/// generic invoke channel.",
    "public struct HostBridge {",
    ...fields,
    "",
    "    public init() {}",
    "}",
    "",
    "extension JSRuntime {",
    "    /// Installs the generated host functions onto `__host` for `target`.",
    "    /// Watch-only functions are absent in the widget so JS feature detection",
    "    /// is correct there and a stray call fails loudly, not silently hangs.",
    "    /// `allowedFeatures` is the HostPolicy ceiling (ARCH-07): nil installs",
    '    /// everything the target backs; otherwise only allowed features\' methods',
    '    /// are installed — except "core" (commit/log/timers/invoke), which is',
    "    /// always installed because the runtime can't operate without it.",
    "    func installHostBridge(",
    "        into host: JSValue, context: OpaquePointer, target: HostTarget,",
    "        allowedFeatures: Set<String>?",
    "    ) {",
    "        func allows(_ feature: String) -> Bool {",
    "            allowedFeatures?.contains(feature) ?? true",
    "        }",
    ...sharedInstalls,
    ...targetedBlock(watchOnlyInstalls, "watch"),
    ...targetedBlock(widgetOnlyInstalls, "widget"),
    "    }",
    "}",
    "",
    "// @convention(c) trampolines: no captures, so each recovers its JSRuntime",
    "// from the context opaque pointer, marshals the args, and dispatches.",
    "",
    ...directMethods.map(swiftTrampoline).flatMap((t) => [t, ""]),
  ]
    .join("\n")
    .trimEnd()}\n`;
}

/** The TS `QuickJSHostGlobal` interface — the raw string/number bridge JS sees. */
function quickJSHostGlobalTS() {
  const lines = [
    "/** Raw globals installed by the host before the bundle is evaluated",
    " *  (generated from the schema's direct methods). Strings/numbers cross the C",
    ' *  boundary; commit/event payloads are JSON strings. `via:"invoke"` methods',
    " *  are routed through `invoke`, not installed here. */",
    "export interface QuickJSHostGlobal {",
  ];
  for (const m of directMethods) {
    if (m.doc) lines.push(`  /** ${m.doc} */`);
    const params = argsOf(m)
      .map((a) => `${a.name}: ${TS_ARG[a.type]}`)
      .join(", ");
    const opt = m.tsRequired ? "" : "?";
    lines.push(`  ${m.name}${opt}(${params}): ${TS_RET[retOf(m)]};`);
  }
  lines.push("}");
  return lines.join("\n");
}

