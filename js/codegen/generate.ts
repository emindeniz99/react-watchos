function tsInterface(def: StructDef | TsOnlyDef) {
  const lines: string[] = [];
  if (def.doc) lines.push(`/** ${def.doc} */`);
  lines.push(`export interface ${def.ts} {`);
  for (const f of def.fields) {
    const opt = f.optional ? "?" : "";
    const doc = f.doc ? ` // ${f.doc}` : "";
    lines.push(`  ${f.name}${opt}: ${f.ts};${doc}`);
  }
  lines.push("}");
  return lines.join("\n");
}

/** A closed string union rendered one member per line — the vocabularies
 *  (health types, workout activity types) that Swift must switch over too. */
function tsUnion(name: string, members: string[], doc: string) {
  return [
    `/** ${doc} */`,
    `export type ${name} =`,
    ...members.map((m) => `  | "${m}"`),
    "  ;",
  ].join("\n");
}

function tsModel() {
  const parts = [
    banner(),
    "/* eslint-disable */",
    "export type JSONValue =",
    "  | string | number | boolean | JSONValue[]",
    "  | { [key: string]: JSONValue } | null;",
    "",
    `export interface ${node.ts} {`,
    "  id: number;",
    "  type: string;",
    "  props: Record<string, unknown>;",
    `  children: ${node.ts}[];`,
    "}",
    "",
    tsUnion(
      "HealthQuantityType",
      healthQuantityTypes,
      "The HealthKit quantity types this bridge reads. Closed: an unbound " +
        "type would type-check and resolve null forever.",
    ),
    "",
    tsUnion(
      "WorkoutActivityType",
      workoutActivityTypes,
      "Every live HKWorkoutActivityType member (the 3 deprecated spellings " +
        "excluded). Swift maps the NAME to the case; raw values are " +
        "undocumented.",
    ),
  ];
  for (const def of [...structs, ...tsOnly, ...invokeShapes])
    parts.push("", tsInterface(def));
  const manifest = JSON.stringify(
    hostMethods.map((m) => ({
      name: m.name,
      targets: m.targets,
      feature: m.feature,
      since: m.since,
      ...(m.via ? { via: m.via } : {}),
    })),
  );
  parts.push(
    "",
    "/** Native bridge methods: which runtime installs each, the capability",
    " *  `feature` an OTA bundle gates on, and the bridgeProtocol it shipped in. */",
    `export const HOST_METHODS = ${manifest} as const;`,
    "",
    "/** Committed-tree wire version (SerializedTree.v). Bump on shape changes. */",
    `export const WIRE_VERSION = ${wireVersion} as const;`,
    "",
    "/** JS<->Swift host bridge protocol version (ARCH-01). */",
    `export const BRIDGE_PROTOCOL = ${bridgeProtocol} as const;`,
    "",
    "/** Capability features each native target provides (ARCH-01). */",
    `export const HOST_FEATURES = ${JSON.stringify({
      watch: featuresFor("watch"),
      widget: featuresFor("widget"),
    })} as const;`,
    "",
    "/** The component contract (CX-024): every primitive the tree can emit and",
    " *  how the widget interpreter supports it (full | degraded). Both Swift",
    " *  interpreters are drift-tested against this. */",
    `export const COMPONENTS = ${JSON.stringify(components)} as const;`,
    "",
    invokeShapesTS(),
    "",
    quickJSHostGlobalTS(),
  );
  return `${parts.join("\n")}\n`;
}

// --- Workout activity names (watchOS host) ---------------------------------
// The other half of the `workoutActivityTypes` vocabulary: JS sends the case
// NAME and Swift needs an HKWorkoutActivityType. `HKWorkoutActivityType` is an
// ObjC NS_ENUM with UInt raw values that Apple does NOT document, so a numeric
// round trip could silently land on a different activity — the mapping has to
// be a name switch, and generating it from the same list the TS union comes
// from is what makes name-vs-case drift impossible. Lives in ReactWatchHost
// (it imports HealthKit) and compiles out off-watchOS like the rest of it.

function workoutActivityNameSwift() {
  return `${[
    banner(),
    "#if os(watchOS)",
    "import HealthKit",
    "",
    "/// Maps a wire `WorkoutActivityType` name to its HKWorkoutActivityType",
    "/// case. `nil` = a name this binary doesn't know, which the workout",
    "/// handler rejects INVALID_REQUEST rather than silently starting `.other`.",
    "enum WorkoutActivityName {",
    "    static func type(for name: String) -> HKWorkoutActivityType? {",
    "        switch name {",
    ...workoutActivityTypes.map((n) => `        case "${n}": .${n}`),
    "        default: nil",
    "        }",
    "    }",
    "",
    "    /// The same table read backwards, for the one session this process does",
    "    /// NOT construct from a wire payload: a workout recovered from a launch",
    "    /// that crashed. HealthKit hands back the session and its",
    "    /// `HKWorkoutConfiguration`, so the activity arrives as a case and has to",
    "    /// be named before `getWorkoutState()` can report it. `nil` = a case this",
    "    /// vocabulary excludes (the three deprecated spellings), and the snapshot",
    "    /// then OMITS `activityType` rather than naming the wrong workout.",
    "    static func name(for type: HKWorkoutActivityType) -> String? {",
    "        switch type {",
    ...workoutActivityTypes.map((n) => `        case .${n}: "${n}"`),
    "        default: nil",
    "        }",
    "    }",
    "}",
    "#endif",
  ]
    .join("\n")
    .trimEnd()}\n`;
}

